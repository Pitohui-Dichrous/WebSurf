"""Convert the vendored, unmodified Lucide SVG geometry into Android path data.
Run after deliberately updating assets/icons/lucide/provenance.json and its SVGs.
No network or design changes are performed by this conversion.
"""
from pathlib import Path
import json
import xml.etree.ElementTree as ET
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
ICONS = ROOT / "assets/icons/lucide"


def number(value):
    return format(float(value), ".8g")


def paths(svg):
    result = []
    root = ET.parse(svg).getroot()
    assert root.get("viewBox") == "0 0 24 24"
    assert root.get("fill") == "none" and root.get("stroke-width") == "2"
    for node in root:
        tag, a = node.tag.split("}")[-1], node.attrib
        if tag == "path":
            result.append(a["d"])
        elif tag == "line":
            result.append(f'M{a["x1"]},{a["y1"]} L{a["x2"]},{a["y2"]}')
        elif tag == "circle":
            x, y, r = (float(a[k]) for k in ("cx", "cy", "r"))
            result.append(f'M{number(x+r)},{number(y)} A{number(r)},{number(r)} 0 1,0 {number(x-r)},{number(y)} A{number(r)},{number(r)} 0 1,0 {number(x+r)},{number(y)} Z')
        elif tag == "rect":
            x, y, w, h = (float(a.get(k, "0")) for k in ("x", "y", "width", "height"))
            rx = min(float(a.get("rx", a.get("ry", "0"))), w / 2)
            ry = min(float(a.get("ry", a.get("rx", "0"))), h / 2)
            if rx and ry:
                result.append(f'M{number(x+rx)},{number(y)} H{number(x+w-rx)} A{number(rx)},{number(ry)} 0 0,1 {number(x+w)},{number(y+ry)} V{number(y+h-ry)} A{number(rx)},{number(ry)} 0 0,1 {number(x+w-rx)},{number(y+h)} H{number(x+rx)} A{number(rx)},{number(ry)} 0 0,1 {number(x)},{number(y+h-ry)} V{number(y+ry)} A{number(rx)},{number(ry)} 0 0,1 {number(x+rx)},{number(y)} Z')
            else:
                result.append(f'M{number(x)},{number(y)} h{number(w)} v{number(h)} h{number(-w)} Z')
        else:
            raise ValueError(f"Unsupported SVG primitive: {tag}")
    return result


def main():
    provenance = json.loads((ICONS / "provenance.json").read_text(encoding="utf-8"))
    table = {p.stem: paths(p) for p in sorted(ICONS.glob("*.svg"))}
    output = ['package io.websurf.app;', '', '/** Official Lucide SVG geometry. Generated by scripts/import_icons.py; do not draw replacements. */', 'final class ImportedIcons {', '  private ImportedIcons() {}', '', '  static String[] paths(String kind) {', '    return switch (kind) {']
    for kind, source in provenance["aliases"].items():
        if kind == "globe":
            continue
        data = ", ".join(json.dumps(p) for p in table[source])
        output.append(f'      case "{kind}" -> new String[] {{{data}}};')
    fallback = ", ".join(json.dumps(p) for p in table[provenance["aliases"]["globe"]])
    output.extend([f'      default -> new String[] {{{fallback}}};', '    };', '  }', '}', ''])
    (ROOT / "app/src/main/java/io/websurf/app/ImportedIcons.java").write_text("\n".join(output),encoding="utf-8")
    resource_dir = ROOT / "app/src/main/res/drawable"
    for name, data in table.items():
        xml = ['<?xml version="1.0" encoding="utf-8"?>', '<!-- Lucide Icons: ISC and Feather-derived MIT. See assets/licenses/Lucide-LICENSE.txt. -->', '<vector xmlns:android="http://schemas.android.com/apk/res/android"', '    android:width="24dp" android:height="24dp"', '    android:viewportWidth="24" android:viewportHeight="24">']
        for d in data:
            xml.append('    <path android:fillColor="@android:color/transparent" android:strokeColor="#FF000000" android:strokeWidth="2" android:strokeLineCap="round" android:strokeLineJoin="round" android:pathData="'+escape(d,{'"':'&quot;'})+'" />')
        xml.extend(['</vector>', ''])
        (resource_dir / ('ws_lucide_'+name.replace('-', '_')+'.xml')).write_text("\n".join(xml),encoding="utf-8")
    print(f'Converted {len(table)} official SVG icons, commit {provenance["commit"]}')


if __name__ == "__main__":
    main()
